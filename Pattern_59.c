/* Print below pattern.
   
 
1 A 1
2 B 2
3 C 3
 
*/       

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
#include <stdio.h>

int main() 
{
    int i;
    char ch = 'A';
    
    for (i = 1; i <= 3; i++) 
    {
        printf("%d %c %d", i, ch, i);
        ch++;
        
        printf("\n");
    }
    
    return 0;
}



