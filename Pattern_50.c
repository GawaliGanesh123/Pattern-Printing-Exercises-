/* Print below pattern.
   
 
D4 C3 B2 A1
D4 C3 B2 A1
D4 C3 B2 A1
D4 C3 B2 A1
 
*/       

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k;
    char ch;
    
    for (i = 1; i <= 4; i++) 
    {
        ch = 'D';
        k = 4;
        
        for (j = 1; j <= 4; j++) 
        {
            printf("%c%d ", ch, k);
            ch--;
            k--;
        }
        printf("\n");
    }
    
    return 0;
}