/* Print below pattern.
   
 
4 3 2 1
5 4 3 2
6 5 4 3
7 6 5 4
 
*/       

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k;
    
    for (i = 1; i <= 4; i++) 
    {
        k = i + 3;
        
        for (j = 1; j <= 4; j++) 
        {
            printf("%d ", k);
            k--;
        }
        printf("\n");
    }
    
    return 0;
}