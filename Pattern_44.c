/* Print below pattern.
   
 
A B C
1 2 3
D E F
4 5 6
G H I
7 8 9
 
*/       

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k = 1;
    char ch = 'A';
    
    for (i = 1; i <= 6; i++) 
    {
        for (j = 1; j <= 3; j++) 
        {
            if (i % 2 != 0)
            {
                printf("%c ", ch);
                ch++;
            }
            else
            {
                printf("%d ", k);
                k++;
            }
        }
        printf("\n");
    }
    
    return 0;
}
