/* Print below pattern.
   
 
1 2 3
6 5 4
7 8 9
 
*/       

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k = 1, l;
    
    for (i = 1; i <= 3; i++) 
    {
        if (i % 2 != 0)
        {
            for (j = 1; j <= 3; j++) 
            {
                printf("%d ", k);
                k++;
            }
        }
        else
        {
            l = k + 2;
            
            for (j = 1; j <= 3; j++) 
            {
                printf("%d ", l);
                l--;
            }
            
            k = k + 3;
        }
        
        printf("\n");
    }
    
    return 0;
}


