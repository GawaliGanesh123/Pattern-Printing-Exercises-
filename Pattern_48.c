/* Print below pattern.
   
 
1 2 9 4
25 6 49 8
81 10 121 12
169 14 225 16
 
*/       

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k = 1;
    
    for (i = 1; i <= 4; i++) 
    {
        for (j = 1; j <= 4; j++) 
        {
            if (k % 2 != 0)
            {
                printf("%d ", k * k);
            }
            else
            {
                printf("%d ", k);
            }
            
            k++;
        }
        printf("\n");
    }
    
    return 0;
}



