/* Print below pattern.
   
 
2 5 10
17 26 37
50 65 82
 
*/       

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k = 1;
    
    for (i = 1; i <= 3; i++) 
    {
        for (j = 1; j <= 3; j++) 
        {
            printf("%d ", (k * k) + 1);
            k++;
        }
        printf("\n");
    }
    
    return 0;
}