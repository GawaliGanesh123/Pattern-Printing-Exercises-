/* Print below pattern.
   
 
5
6 8
7 10 13
8 12 16 20
9 14 19 24 29
 
*/       

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k;
    
    for (i = 1; i <= 5; i++) 
    {
        k = i + 4;
        
        for (j = 1; j <= i; j++) 
        {
            printf("%d ", k);
            k = k + i;
        }
        printf("\n");
    }
    
    return 0;
}



