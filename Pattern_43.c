/* Print below pattern.
   
 
A 2 C 4
E 6 G 8
I 10 K 12
 
*/       

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  
    
#include <stdio.h>

int main() 
{
    int i, j, k = 2;
    char ch = 'A';
    
    for (i = 1; i <= 3; i++) 
    {
        for (j = 1; j <= 4; j++) 
        {
            if (j % 2 != 0)
            {
                printf("%c ", ch);
                ch = ch + 2;
            }
            else
            {
                printf("%d ", k);
                k = k + 2;
            }
        }
        printf("\n");
    }
    
    return 0;
}



